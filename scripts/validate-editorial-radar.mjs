#!/usr/bin/env node

import { existsSync, readFileSync, statSync } from "node:fs";

const failures = [];

function fail(message) {
  failures.push(message);
}

function read(path) {
  return readFileSync(path, "utf8");
}

function requireFile(path) {
  if (!existsSync(path)) {
    fail(`${path} is missing`);
    return "";
  }
  if (!statSync(path).isFile()) {
    fail(`${path} is not a file`);
    return "";
  }
  return read(path);
}

function requireIncludes(path, text, phrases) {
  for (const phrase of phrases) {
    if (!text.includes(phrase)) {
      fail(`${path} is missing required phrase: ${phrase}`);
    }
  }
}

const contractPath = "docs/editorial-radar.md";
const sourcesPath = "data/research-sources.yaml";
const signalsPath = "data/research-signals.json";
const workflowPath = ".github/workflows/editorial-radar.md";
const lockPath = ".github/workflows/editorial-radar.lock.yml";
const specPath = "docs/superpowers/specs/2026-08-27-editorial-research-radar.md";
const planPath = "docs/superpowers/plans/2026-08-27-issue-78-editorial-research-radar.md";

const contract = requireFile(contractPath);
const sources = requireFile(sourcesPath);
const signalsText = requireFile(signalsPath);
const workflow = requireFile(workflowPath);
const lock = requireFile(lockPath);
const spec = requireFile(specPath);
const plan = requireFile(planPath);
const readme = requireFile("README.md");

if (contract) {
  requireIncludes(contractPath, contract, [
    "external sources -> research agent -> research issue -> Ranjib review",
    "Disallowed path",
    "Evidence Hierarchy",
    "Lived-Experience Test",
    "Trend-Chasing Rejection Criteria",
    "Freshness Classes",
    "Research Scoring Rubric",
    "Privacy Rules",
    "Allowed Automated Outputs",
    "Prohibited Autonomous Outputs",
    "Human Approval Boundaries",
    "First Drift Fixture",
  ]);
}

if (sources) {
  requireIncludes(sourcesPath, sources, [
    "schema_version: editorial-research-sources-v1",
    "authority_levels:",
    "domains:",
    "sre:",
    "genai:",
    "open_source_physical_computing:",
    "hobbies:",
    "prefer_primary_sources: true",
  ]);

  const urls = [...sources.matchAll(/^\s+url:\s+(\S+)/gm)].map((match) => match[1]);
  if (urls.length < 20) {
    fail(`${sourcesPath} should include at least 20 source URLs; found ${urls.length}`);
  }
  for (const url of urls) {
    try {
      const parsed = new URL(url);
      if (!["https:"].includes(parsed.protocol)) {
        fail(`${sourcesPath} contains non-HTTPS source URL: ${url}`);
      }
    } catch {
      fail(`${sourcesPath} contains invalid source URL: ${url}`);
    }
  }
}

if (signalsText) {
  let signals;
  try {
    signals = JSON.parse(signalsText);
  } catch (error) {
    fail(`${signalsPath} is not valid JSON: ${error.message}`);
  }

  if (signals) {
    if (signals.schema_version !== "editorial-research-signals-v1") {
      fail(`${signalsPath} has unexpected schema_version`);
    }
    if (!Array.isArray(signals.signals)) {
      fail(`${signalsPath} must contain a signals array`);
    } else {
      for (const [index, signal] of signals.signals.entries()) {
        for (const field of [
          "topic",
          "first_seen",
          "last_seen",
          "occurrences",
          "sources",
          "velocity",
          "editorial_lane",
          "related_posts",
          "related_issues",
          "status",
        ]) {
          if (!(field in signal)) {
            fail(`${signalsPath} signal ${index} is missing ${field}`);
          }
        }
        if (!Array.isArray(signal.sources)) {
          fail(`${signalsPath} signal ${index} sources must be an array`);
        }
        if (!Array.isArray(signal.related_posts)) {
          fail(`${signalsPath} signal ${index} related_posts must be an array`);
        }
        if (!Array.isArray(signal.related_issues)) {
          fail(`${signalsPath} signal ${index} related_issues must be an array`);
        }
        if (!["ignore", "watch", "experiment", "update-existing", "write", "seed"].includes(signal.status)) {
          fail(`${signalsPath} signal ${index} has invalid status: ${signal.status}`);
        }
      }
    }
  }
}

if (workflow) {
  requireIncludes(workflowPath, workflow, [
    "engine: codex",
    "workflow_dispatch:",
    "tools:",
    "web-search:",
    "safe-outputs:",
    "create-issue:",
    "Read `docs/editorial-radar.md` first",
    "Do not create articles",
    "Do not modify published content",
  ]);
}

if (lock) {
  requireIncludes(lockPath, lock, [
    "# gh-aw-metadata:",
    "This file was automatically generated by gh-aw",
    "agent_id\":\"codex\"",
    "CODEX_API_KEY",
    "OPENAI_API_KEY",
  ]);
}

if (spec) {
  requireIncludes(specPath, spec, [
    "Goal",
    "Scope",
    "Architecture",
    "Agentic Workflow MVP",
    "Non-Goals",
  ]);
}

if (plan) {
  requireIncludes(planPath, plan, [
    "REQUIRED SUB-SKILL",
    "Task 1",
    "Task 2",
    "Task 3",
    "Task 4",
    "Task 5",
    "hugo --gc --minify",
  ]);
}

if (readme) {
  if (readme.includes("Anatole theme") || readme.includes("themes/anatole") || readme.includes("git submodule update --init --recursive")) {
    fail("README.md still contains stale Anatole theme/submodule guidance");
  }
  requireIncludes("README.md", readme, [
    "There is no Hugo theme submodule.",
    "docs/systems-in-practice-hub.md",
  ]);
}

if (failures.length > 0) {
  console.error("Editorial radar validation failed:");
  for (const failure of failures) {
    console.error(`- ${failure}`);
  }
  process.exit(1);
}

console.log("Editorial radar validation passed.");
