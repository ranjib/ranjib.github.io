func writeFile(t *testing.T, root, path, contents string) {
	t.Helper()

	fullPath := filepath.Join(root, filepath.FromSlash(path))
	if err := os.MkdirAll(filepath.Dir(fullPath), 0o755); err != nil {
		t.Fatalf("creating fixture directory: %v", err)
	}
	if err := os.WriteFile(fullPath, []byte(contents), 0o644); err != nil {
		t.Fatalf("writing fixture file %s: %v", path, err)
	}
}

func assertFailureContains(t *testing.T, failures []string, want string) {
	t.Helper()

	for _, failure := range failures {
		if strings.Contains(failure, want) {
			return
		}
	}
	t.Fatalf("expected failure containing %q, got:\n%s", want, strings.Join(failures, "\n"))
}

