func TestValidateAcceptsCompleteFixture(t *testing.T) {
	root := writeFixture(t)

	failures := Validate(root)
	if len(failures) > 0 {
		t.Fatalf("Validate returned failures:\n%s", strings.Join(failures, "\n"))
	}
}

func TestValidateRejectsInvalidSourceURL(t *testing.T) {
	root := writeFixture(t)
	writeFile(t, root, sourcesPath, strings.Replace(validSources(), "https://sre.google/", "http://sre.google/", 1))

	failures := Validate(root)
	assertFailureContains(t, failures, "non-HTTPS source URL")
}

func TestValidateRejectsUnknownSignalField(t *testing.T) {
	root := writeFixture(t)
	writeFile(t, root, signalsPath, `{
  "schema_version": "editorial-research-signals-v1",
  "updated_at": "2026-08-27T00:00:00Z",
  "signals": [],
  "surprise": true
}`)

	failures := Validate(root)
	assertFailureContains(t, failures, "unknown field")
}

func TestValidateRejectsStaleReadmeGuidance(t *testing.T) {
	root := writeFixture(t)
	writeFile(t, root, readmePath, "The Anatole theme lives in themes/anatole as a git submodule.\n")

	failures := Validate(root)
	assertFailureContains(t, failures, "stale Anatole theme/submodule guidance")
}

